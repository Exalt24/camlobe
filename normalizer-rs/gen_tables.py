# LIFESPAN: permanent
"""Write src/tables.rs from the Python that is the reference, so the port can never disagree with it about a character.

`catalog/normalize.py` calls two things whose answers depend on the Unicode version baked into the interpreter: `str.upper()`
and `str.isalpha()`. Rust's standard library and the crates that carry the same tables are on other Unicode versions (the
sweep in tests/test_normalize_rust.py found 4,308 cases where they disagreed with Python 3.13), so the port does not use
them. It reads these two tables, generated here from the interpreter, and uses `unicode-normalization` (pinned to the same
Unicode version) only for NFKC and NFD, which the same sweep checks.

    python normalizer-rs/gen_tables.py        # rewrites src/tables.rs; run it again after changing the Python version
"""
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent / "src" / "tables.rs"


def code_points():
    for cp in range(0x110000):
        if not 0xD800 <= cp <= 0xDFFF:
            yield cp


def letter_ranges():
    ranges, start, prev = [], None, None
    for cp in code_points():
        if chr(cp).isalpha():
            if start is None:
                start = prev = cp
            elif cp == prev + 1:
                prev = cp
            else:
                ranges.append((start, prev))
                start = prev = cp
        elif start is not None:
            ranges.append((start, prev))
            start = prev = None
    if start is not None:
        ranges.append((start, prev))
    return ranges


def upper_entries():
    return [(cp, chr(cp).upper()) for cp in code_points() if chr(cp).upper() != chr(cp)]


def rust_str(text):
    return '"' + "".join(f"\\u{{{ord(c):X}}}" for c in text) + '"'


def main():
    letters, upper = letter_ranges(), upper_entries()
    lines = [
        f"// GENERATED by gen_tables.py from Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}. Do not edit.",
        f'pub const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";',
        "",
        "/// Every range of code points for which Python's str.isalpha() is true.",
        "pub const LETTERS: &[(u32, u32)] = &[",
    ]
    lines += [f"    (0x{a:X}, 0x{b:X})," for a, b in letters]
    lines += ["];", "", "/// Every code point whose str.upper() is not itself, with the full (possibly longer) mapping.", "pub const UPPER: &[(u32, &str)] = &["]
    lines += [f"    (0x{cp:X}, {rust_str(text)})," for cp, text in upper]
    lines += ["];", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{OUT}: {len(letters)} letter ranges, {len(upper)} upper mappings, Unicode {unicodedata.unidata_version}")


if __name__ == "__main__":
    main()
